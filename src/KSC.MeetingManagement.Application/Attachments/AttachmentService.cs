using System.Security.Cryptography;
using KSC.MeetingManagement.Application.Identity;
using KSC.MeetingManagement.Application.Meetings;
using KSC.MeetingManagement.Application.Tenants;
using KSC.MeetingManagement.Domain.Meetings;

namespace KSC.MeetingManagement.Application.Attachments;

public sealed class AttachmentOptions
{
    public const long DefaultMaxBytes = 10 * 1024 * 1024;

    public long MaxBytes { get; set; } = DefaultMaxBytes;
}

public sealed record AttachmentDto(Guid Id, Guid MeetingId, string FileName, string ContentType, long SizeBytes, string Sha256, DateTimeOffset UploadedAtUtc)
{
    public static AttachmentDto From(MeetingAttachment a)
    {
        ArgumentNullException.ThrowIfNull(a);
        return new(a.Id, a.MeetingId, a.FileName, a.ContentType, a.SizeBytes, a.Sha256, a.UploadedAtUtc);
    }
}

public sealed record AttachmentDownload(string FileName, string ContentType, Stream Content);

/// <summary>Persistence port. Implementations must only return attachments of the current tenant.</summary>
public interface IAttachmentRepository
{
    Task<MeetingAttachment?> GetAsync(Guid meetingId, Guid attachmentId, CancellationToken cancellationToken);

    Task<IReadOnlyList<MeetingAttachment>> ListAsync(Guid meetingId, CancellationToken cancellationToken);

    Task AddAsync(MeetingAttachment attachment, CancellationToken cancellationToken);

    void Remove(MeetingAttachment attachment);

    Task SaveChangesAsync(CancellationToken cancellationToken);
}

/// <summary>Binary storage port. Keys are opaque and generated by the application, never taken from user input.</summary>
public interface IFileStore
{
    Task SaveAsync(string key, ReadOnlyMemory<byte> content, CancellationToken cancellationToken);

    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

public sealed class AttachmentService(
    IAttachmentRepository attachments,
    IMeetingRepository meetings,
    IFileStore files,
    ITenantContext tenant,
    ICurrentUser user,
    TimeProvider clock,
    AttachmentOptions options)
{
    // Extension -> (content type served on download, signature check). The client-supplied content type is ignored.
    private static readonly Dictionary<string, (string ContentType, Func<byte[], bool> Matches)> Allowed = new(StringComparer.OrdinalIgnoreCase)
    {
        [".pdf"] = ("application/pdf", b => StartsWith(b, 0x25, 0x50, 0x44, 0x46)),
        [".png"] = ("image/png", b => StartsWith(b, 0x89, 0x50, 0x4E, 0x47)),
        [".jpg"] = ("image/jpeg", b => StartsWith(b, 0xFF, 0xD8, 0xFF)),
        [".jpeg"] = ("image/jpeg", b => StartsWith(b, 0xFF, 0xD8, 0xFF)),
        [".docx"] = ("application/vnd.openxmlformats-officedocument.wordprocessingml.document", b => StartsWith(b, 0x50, 0x4B, 0x03, 0x04)),
        [".xlsx"] = ("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", b => StartsWith(b, 0x50, 0x4B, 0x03, 0x04)),
        [".pptx"] = ("application/vnd.openxmlformats-officedocument.presentationml.presentation", b => StartsWith(b, 0x50, 0x4B, 0x03, 0x04)),
        [".txt"] = ("text/plain", b => !b.Contains((byte)0)),
    };

    public static IReadOnlyCollection<string> AllowedExtensions => Allowed.Keys;

    /// <summary>Stores a file. Returns null if the meeting does not exist in the current tenant.</summary>
    public async Task<AttachmentDto?> UploadAsync(Guid meetingId, string? fileName, Stream content, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        if (await meetings.GetAsync(meetingId, cancellationToken) is null)
        {
            return null;
        }

        var safeName = SanitizeFileName(fileName);
        var extension = Path.GetExtension(safeName);
        if (!Allowed.TryGetValue(extension, out var rule))
        {
            throw new MeetingDomainException($"File type '{extension}' is not allowed.");
        }

        var bytes = await ReadLimitedAsync(content, options.MaxBytes, cancellationToken);
        if (bytes.Length == 0)
        {
            throw new MeetingDomainException("The file is empty.");
        }

        if (!rule.Matches(bytes))
        {
            throw new MeetingDomainException("The file content does not match its extension.");
        }

        var key = $"{tenant.RequiredTenantId:N}/{Guid.NewGuid():N}";
        var attachment = new MeetingAttachment(
            Guid.NewGuid(), tenant.RequiredTenantId, meetingId, safeName, rule.ContentType, bytes.Length,
            Convert.ToHexString(SHA256.HashData(bytes)), key, user.RequiredUserId, clock.GetUtcNow());

        await files.SaveAsync(key, bytes, cancellationToken);
        try
        {
            await attachments.AddAsync(attachment, cancellationToken);
            await attachments.SaveChangesAsync(cancellationToken);
        }
        catch
        {
            await files.DeleteAsync(key, CancellationToken.None);
            throw;
        }

        return AttachmentDto.From(attachment);
    }

    public async Task<IReadOnlyList<AttachmentDto>> ListAsync(Guid meetingId, CancellationToken cancellationToken) =>
        (await attachments.ListAsync(meetingId, cancellationToken)).Select(AttachmentDto.From).ToList();

    public async Task<AttachmentDownload?> DownloadAsync(Guid meetingId, Guid attachmentId, CancellationToken cancellationToken)
    {
        if (await attachments.GetAsync(meetingId, attachmentId, cancellationToken) is not { } attachment
            || await files.OpenReadAsync(attachment.StorageKey, cancellationToken) is not { } stream)
        {
            return null;
        }

        return new AttachmentDownload(attachment.FileName, attachment.ContentType, stream);
    }

    public async Task<bool> DeleteAsync(Guid meetingId, Guid attachmentId, CancellationToken cancellationToken)
    {
        if (await attachments.GetAsync(meetingId, attachmentId, cancellationToken) is not { } attachment)
        {
            return false;
        }

        attachments.Remove(attachment);
        await attachments.SaveChangesAsync(cancellationToken);
        await files.DeleteAsync(attachment.StorageKey, cancellationToken);
        return true;
    }

    internal static string SanitizeFileName(string? fileName)
    {
        // Browsers may send a full path; keep only the final segment and drop control and path characters.
        var name = (fileName ?? string.Empty).Replace('\\', '/');
        name = name[(name.LastIndexOf('/') + 1)..];
        name = new string(name.Where(c => !char.IsControl(c) && c != ':' && c != '"' && c != '<' && c != '>' && c != '|' && c != '?' && c != '*').ToArray()).Trim();
        if (name.Length == 0 || name.StartsWith('.'))
        {
            throw new MeetingDomainException("A valid file name is required.");
        }

        return name.Length > 200 ? name[^200..] : name;
    }

    private static async Task<byte[]> ReadLimitedAsync(Stream content, long maxBytes, CancellationToken cancellationToken)
    {
        using var buffer = new MemoryStream();
        var chunk = new byte[81920];
        int read;
        while ((read = await content.ReadAsync(chunk, cancellationToken)) > 0)
        {
            buffer.Write(chunk, 0, read);
            if (buffer.Length > maxBytes)
            {
                throw new AttachmentTooLargeException(maxBytes);
            }
        }

        return buffer.ToArray();
    }

    private static bool StartsWith(byte[] bytes, params byte[] prefix) =>
        bytes.Length >= prefix.Length && bytes.AsSpan(0, prefix.Length).SequenceEqual(prefix);
}

public sealed class AttachmentTooLargeException(long maxBytes)
    : InvalidOperationException($"The file exceeds the maximum size of {maxBytes} bytes.");
